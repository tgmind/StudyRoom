import json
import os

with open("public/avatars/manifest.json", "r") as f:
    full_manifest = json.load(f)

avatars = full_manifest["avatars"]
categories = full_manifest["categories"]

ts_content = """// Auto-generated by scripts/extract_avatars.py. DO NOT EDIT DIRECTLY.

export interface AvatarItem {
  id: string;
  label: string;
  category: string;
  assetPath: string;
}

export const AVATAR_CATEGORIES = [
"""

for cat in categories:
    ts_content += f'  "{cat}",\n'

ts_content += """] as const;

export type AvatarCategory = typeof AVATAR_CATEGORIES[number];

export const AVATAR_ITEMS: AvatarItem[] = [
"""

for a in avatars:
    ts_content += f"""  {{
    id: "{a['id']}",
    label: "{a['label']}",
    category: "{a['category']}",
    assetPath: "{a['asset_path']}",
  }},
"""

ts_content += """];

export const AVATAR_MAP = new Map<string, AvatarItem>(
  AVATAR_ITEMS.map((item) => [item.id, item])
);

export const DEFAULT_AVATAR_ID = "avatar-1-01";
export const DEFAULT_AVATAR_PATH = "/avatars/optimized/avatar-1-01.webp";

/**
 * Returns all available avatar items.
 */
export function getAllAvatars(): AvatarItem[] {
  return AVATAR_ITEMS;
}

/**
 * Retrieves an avatar item by its unique ID.
 */
export function getAvatarById(id: string | null | undefined): AvatarItem | undefined {
  if (!id) return undefined;
  return AVATAR_MAP.get(id);
}

/**
 * Validates whether an avatar ID exists in the approved manifest.
 */
export function isValidAvatarId(id: string | null | undefined): boolean {
  if (!id) return false;
  return AVATAR_MAP.has(id);
}

/**
 * Returns avatars filtered by category. If category is "All", returns all avatars.
 */
export function getAvatarsByCategory(category: string): AvatarItem[] {
  if (!category || category === "All") {
    return AVATAR_ITEMS;
  }
  return AVATAR_ITEMS.filter((item) => item.category === category);
}

/**
 * Universally resolves an avatar URL from either avatarId, avatarUrl, or fallback.
 */
export function resolveAvatarUrl(
  avatarId?: string | null,
  avatarUrl?: string | null
): string | null {
  if (avatarId && AVATAR_MAP.has(avatarId)) {
    return AVATAR_MAP.get(avatarId)!.assetPath;
  }
  if (avatarUrl) {
    if (avatarUrl.startsWith("/") || avatarUrl.startsWith("http://") || avatarUrl.startsWith("https://") || avatarUrl.startsWith("data:")) {
      return avatarUrl;
    }
    // Check if avatarUrl itself is an avatarId
    if (AVATAR_MAP.has(avatarUrl)) {
      return AVATAR_MAP.get(avatarUrl)!.assetPath;
    }
    // Check if it's formatted as avatar-x-xx
    if (/^avatar-\\d-\\d{2}$/.test(avatarUrl)) {
      return `/avatars/optimized/${avatarUrl}.webp`;
    }
    return avatarUrl;
  }
  return null;
}
"""

os.makedirs("lib/avatars", exist_ok=True)
with open("lib/avatars/manifest.ts", "w") as f:
    f.write(ts_content)

print(f"lib/avatars/manifest.ts successfully generated with {len(avatars)} avatars!")
